#!/usr/bin/env python3
"""Build the Phase 8B modern-compilation package.

Produces a self-contained archive holding everything needed to reproduce the
modern build and to check it:

    sources/          main.tex, sections/, references.bib   (as built)
    build/            main.pdf, main.log, main.blg, main.bbl (genuine BibTeX)
    compile/          the tool-chain bootstrap and build scripts
    verification/     validator output, example checks, PDF inspection,
                      tool-chain provenance
    BUILD_CORRECTIONS.md, README_BUILD.md, FINAL_VALIDATION_REPORT.md
    MANIFEST.sha256

The archive's own SHA-256 and size are written to a sidecar *outside* the
archive, so that the hash can be checked against the file as shipped.

The Phase 8 and Phase 8A archives are not touched.

Usage:  python3 tools/make_modern_package.py [label]
"""
import hashlib
import os
import shutil
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER = os.path.normpath(os.path.join(HERE, ".."))

BUILD_DIR = os.path.join(PAPER, "build_modern")
OUT_DIR = PAPER


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def add_tree(zf, src, prefix, skip=()):
    """Add a directory tree under `prefix`."""
    n = 0
    base = os.path.basename(src.rstrip("/"))
    for dirpath, dirnames, filenames in os.walk(src):
        dirnames[:] = sorted(d for d in dirnames if d not in skip)
        rel = os.path.relpath(dirpath, src)
        for fn in sorted(filenames):
            full = os.path.join(dirpath, fn)
            arc = "/".join(p for p in [prefix, base, "" if rel == "." else rel,
                                       fn] if p)
            zf.write(full, arc)
            n += 1
    return n


def build(label, out_dir):
    name = "MatrixRingManuscript_%s.zip" % label
    arch = os.path.join(out_dir, name)
    staging = os.path.join(out_dir, ".pkg8b")

    shutil.rmtree(staging, ignore_errors=True)
    os.makedirs(staging)

    # ---- sources exactly as built -------------------------------------
    src = os.path.join(staging, "sources")
    os.makedirs(src)
    for f in ("main.tex", "references.bib"):
        shutil.copy2(os.path.join(BUILD_DIR, f), src)
    shutil.copytree(os.path.join(BUILD_DIR, "sections"),
                    os.path.join(src, "sections"))

    # ---- build products ------------------------------------------------
    bld = os.path.join(staging, "build")
    os.makedirs(bld)
    for f in ("main.pdf", "main.log", "main.blg", "main.bbl", "main.aux",
              "main.toc", "main.out"):
        p = os.path.join(BUILD_DIR, f)
        if os.path.exists(p):
            shutil.copy2(p, bld)

    # ---- the tool chain and build scripts ------------------------------
    shutil.copytree(os.path.join(PAPER, "compile"),
                    os.path.join(staging, "compile"))

    # ---- verification evidence ----------------------------------------
    shutil.copytree(os.path.join(BUILD_DIR, "verification"),
                    os.path.join(staging, "verification"))

    # ---- reports -------------------------------------------------------
    for f in ("BUILD_CORRECTIONS.md",):
        shutil.copy2(os.path.join(PAPER, "compile", f), staging)
    for f in ("FINAL_VALIDATION_REPORT.md", "MANUSCRIPT_SELF_AUDIT.md",
              "README.md", "CHANGELOG.md"):
        p = os.path.join(PAPER, f)
        if os.path.exists(p):
            shutil.copy2(p, staging)

    # ---- manifest (of everything except the manifest itself) -----------
    entries = []
    for dirpath, dirnames, filenames in os.walk(staging):
        dirnames[:] = sorted(dirnames)
        for fn in sorted(filenames):
            full = os.path.join(dirpath, fn)
            rel = os.path.relpath(full, staging).replace(os.sep, "/")
            entries.append((rel, os.path.getsize(full), sha256(full)))

    with open(os.path.join(staging, "MANIFEST.sha256"), "w",
              encoding="utf-8") as fh:
        fh.write("# SHA-256 manifest -- Matrix Ring manuscript, %s\n" % label)
        fh.write("# %d files.  Generated by tools/make_modern_package.py.\n"
                 % len(entries))
        fh.write("# The archive's own hash is in the sidecar next to it.\n\n")
        for rel, size, h in entries:
            fh.write("%s  %8d  %s\n" % (h, size, rel))

    # ---- zip ------------------------------------------------------------
    with zipfile.ZipFile(arch, "w", zipfile.ZIP_DEFLATED) as zf:
        for rel, size, h in entries:
            zf.write(os.path.join(staging, rel), rel)
        zf.write(os.path.join(staging, "MANIFEST.sha256"), "MANIFEST.sha256")

    shutil.rmtree(staging, ignore_errors=True)

    digest = sha256(arch)
    size = os.path.getsize(arch)
    with open(arch + ".sha256", "w", encoding="utf-8") as fh:
        fh.write("%s  %s\n" % (digest, os.path.basename(arch)))
        fh.write("# %d bytes, %d entries\n"
                 % (size, len(entries) + 1))

    print("wrote %s" % arch)
    print("  entries : %d" % (len(entries) + 1))
    print("  bytes   : %d" % size)
    print("  sha256  : %s" % digest)
    return arch


def main():
    label = sys.argv[1] if len(sys.argv) > 1 else "20261110_Phase8B"
    for need in ("main.pdf", "main.bbl", "main.log"):
        p = os.path.join(BUILD_DIR, need)
        if not os.path.exists(p):
            sys.exit("make_modern_package.py: missing %s -- run "
                     "compile/build_modern.sh first" % p)
    build(label, OUT_DIR)


if __name__ == "__main__":
    main()
