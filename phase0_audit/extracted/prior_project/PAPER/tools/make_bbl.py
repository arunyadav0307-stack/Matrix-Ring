#!/usr/bin/env python3
"""
make_bbl.py -- produce main.bbl for the manuscript.

WHY THIS EXISTS
---------------
The recovered TeX installation used to render this manuscript (see
compile/README.md) provides **pdfTeX but not BibTeX**: the `bibtex` binary is
absent from the recovered tree and cannot be obtained in this environment.
LaTeX itself only ever *reads* `main.bbl`; the `.bbl` is normally produced by
BibTeX from `references.bib` using a `.bst` style.

This script produces the same artefact --- a `main.bbl` containing a
`thebibliography` environment with one `\\bibitem` per cited entry, in the
Bibliography-with-`plain`-style ordering (sorted by author, numeric labels
[1], [2], ...) --- using the Python BibTeX implementation `pybtex`
(https://pypi.org/project/pybtex/), whose `plain` style reproduces the
ordering and punctuation of BibTeX's `plain.bst`.

It is a *substitute for the bibtex binary*, not a substitute for BibTeX
semantics: if a real `bibtex` is available, prefer it:

    pdflatex main && bibtex main && pdflatex main && pdflatex main

and ignore this file.

USAGE
-----
    python3 tools/make_bbl.py [--bib references.bib] [--aux main.aux]
                              [--out main.bbl] [--check]

`--check` verifies that every key cited in the .aux file appears in the .bbl
and exits non-zero otherwise.

REQUIREMENT
-----------
pybtex >= 0.24 (pip install pybtex).  Nothing else: no LaTeX is needed to run
this step.

NOTES ON THE BACKEND
--------------------
The default pybtex LaTeX backend re-escapes `_`, `&`, `#` and `%` through the
`ulatex+` codec.  Our .bib fields already contain LaTeX source (e.g.
`{$M_2(\\mathbb{F}_2)$}`), so re-escaping would corrupt them.  We subclass the
backend and disable escaping, which makes the .bbl a faithful rendering of the
.bib content.
"""

import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))


def read_citations(aux_path):
    """the \\citation{...} keys of an .aux file, in first-appearance order"""
    keys = []
    if not os.path.exists(aux_path):
        return keys
    with open(aux_path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            m = re.match(r"\\citation\{(.*)\}", line.strip())
            if m:
                for k in m.group(1).split(","):
                    k = k.strip()
                    if k and k not in keys:
                        keys.append(k)
    return keys


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bib", default=os.path.join(ROOT, "references.bib"))
    ap.add_argument("--aux", default=os.path.join(ROOT, "main.aux"))
    ap.add_argument("--out", default=os.path.join(ROOT, "main.bbl"))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    try:
        from pybtex.database import parse_file
        from pybtex.plugin import find_plugin
        from pybtex.backends.latex import Backend as LatexBackend
    except ImportError:
        sys.stderr.write(
            "make_bbl.py: pybtex is not installed.\n"
            "  install it with   pip install pybtex\n"
            "  or use a real bibtex binary instead of this script.\n")
        return 2

    class RawLatexBackend(LatexBackend):
        """a LaTeX backend that does not re-escape LaTeX source in fields"""

        def format_str(self, str_):
            return str_

    bib = parse_file(args.bib)
    style = find_plugin("pybtex.style.formatting", "plain")()
    backend = RawLatexBackend()

    cited = read_citations(args.aux)
    unknown = [k for k in cited if k not in bib.entries]
    if unknown:
        sys.stderr.write("make_bbl.py: cited but not in %s: %s\n"
                         % (os.path.basename(args.bib), ", ".join(unknown)))

    # `plain` sorts by author; pybtex's plain Style does this itself.  The
    # citation list only constrains *which* entries appear.
    entries = [k for k in cited if k in bib.entries] or list(bib.entries.keys())
    formatted = style.format_bibliography(bib, entries)

    import io
    buf = io.StringIO()
    backend.write_to_stream(formatted, buf)
    text = buf.getvalue()
    if not text.endswith("\n"):
        text += "\n"
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write("%% Generated by tools/make_bbl.py using pybtex (plain style).\n")
        fh.write("%% A real BibTeX run with plain.bst produces an equivalent file.\n")
        fh.write("%% Do not edit by hand.\n")
        fh.write(text)

    keys_in_bbl = set(re.findall(r"\\bibitem(?:\[[^\]]*\])?\{([^}]*)\}", text))
    print("make_bbl.py: wrote %s (%d entries, %d bytes)"
          % (args.out, len(keys_in_bbl), len(text)))

    if args.check:
        missing = [k for k in cited if k not in keys_in_bbl]
        if missing:
            sys.stderr.write("make_bbl.py: CHECK FAILED, missing: %s\n"
                             % ", ".join(missing))
            return 1
        print("make_bbl.py: CHECK OK, all %d cited keys present"
              % len(cited))
    return 0


if __name__ == "__main__":
    sys.exit(main())
