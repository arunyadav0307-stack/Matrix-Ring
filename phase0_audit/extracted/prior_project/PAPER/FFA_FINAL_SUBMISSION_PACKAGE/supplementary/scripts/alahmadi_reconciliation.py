                # -> the preimage of C under the F_2-linear map alpha -> sum
                # Build matrix M (rows = N, cols = 2n) with column i = imgs[i]
                M = [[imgs[i][k] for i in range(len(imgs))] for k in range(N)]
                # we want {alpha : M alpha in C} = preimage; C given by rb/piv
                # condition: after reducing M alpha by rb, result = 0
                cond = []
                for k in range(N):
                    colv = [M[k][i] for i in range(len(imgs))]
                    # reduce the N-vector (M[:,i])_k ... do it vectorially:
                    cond.append(colv)
                # reduce the whole system: for each alpha, v = M alpha must be
                # in C.  Equivalent: the composite (reduce-by-C) o M = 0.
                reds = []
                for i in range(len(imgs)):
                    v = list(imgs[i])
                    for row, pc in zip(rb, piv):
                        if v[pc]:
                            f = v[pc]
                            v = [F2.sub(v[j], F2.mul[f][row[j]]) for j in range(N)]
                    reds.append(v)
                cond = [[reds[i][k] for i in range(len(imgs))] for k in range(N)]
                ns = nullspace(F2, cond, len(imgs))
                # back to F_4^n
                out = []
                for alpha in ns:
                    d = [0] * n
                    for i, a in enumerate(alpha):
                        if a:
                            for e in range(n):
                                d[e] = F4.add[d[e]][F4.mul[basisvecs[i][e]][a]]
                    out.append(tuple(d))
                rb2, piv2 = f4_row_space(F4, out, n) if out else ([], [])
                closed = all(
                    f4_in_span(F4, rb2, piv2,
                               tuple(F4.mul[G][c] for c in row), n)
                    for row in rb2)
                sh = all(
                    f4_in_span(F4, rb2, piv2,
                               tuple([row[-1]] + list(row[:-1])), n)
                    for row in rb2)
                return rb2, piv2, closed, sh

