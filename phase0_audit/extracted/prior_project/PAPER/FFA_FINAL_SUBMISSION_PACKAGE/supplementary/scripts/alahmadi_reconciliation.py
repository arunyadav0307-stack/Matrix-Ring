def ptrim(a):
    a = list(a)
    while a and a[-1] == 0:
        a.pop()
    return a


def padd(F, a, b):
    n = max(len(a), len(b))
    out = [0] * n
    for i, x in enumerate(a):
        out[i] = x
    for i, x in enumerate(b):
        out[i] = F.add[out[i]][x]
    return ptrim(out)


def pmul(F, a, b):
    if not a or not b:
        return []
    out = [0] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        if x:
            for j, y in enumerate(b):
                if y:
                    out[i + j] = F.add[out[i + j]][F.mul[x][y]]
    return ptrim(out)


def pdivmod(F, a, b):
    a = list(a)
    db = len(b) - 1
    q = [0] * max(0, len(a) - db)
    for i in range(len(a) - 1, db - 1, -1):
        c = a[i]
        if c:
            q[i - db] = c
            for j in range(db + 1):
                a[i - db + j] = F.sub(a[i - db + j], F.mul[c][b[j]])
    return ptrim(q), ptrim(a[:db])


def pmod(F, a, b):
    return pdivmod(F, a, b)[1]


def pmul_modXn(F, a, b, n):
    """product in F_4[X]/<X^n-1>"""
    p = pmul(F, a, b)
    out = [0] * n
    for i, x in enumerate(p):
        out[i % n] = F.add[out[i % n]][x]
    return ptrim(out)


def redXn(F, p, n):
    """reduce a polynomial modulo X^n - 1 (coefficients fold cyclically)"""
    out = [0] * n
    for i, c in enumerate(p):
        out[i % n] = F.add[out[i % n]][c]
    return ptrim(out)


def reciprocal(F, f):
    """f*(X) = X^deg f f(1/X), made monic"""
    d = len(f) - 1
    out = list(reversed(f))
    # normalise to monic
    lead = out[-1]
    return [F.div(c, lead) for c in out]


def ideal_of_basis(F, p, n):
    """F_4-basis of the ideal (p) of B = F_4[X]/<X^n-1>, as F_4-subspace of
    F_4^n (list of length-n tuples over F_4)."""
    rows = []
    cur = list(redXn(F, p, n)) + [0] * n
    cur = cur[:n]
    for k in range(n):
        v = [0] * n
        for i, c in enumerate(cur):
            v[i] = c
        rows.append(tuple(v))
        # multiply by X
        cur = [cur[-1]] + cur[:-1]
    # F_4-row space
    F2 = FiniteField(2, 1)
    # work over F_4 via the library rref (needs a field -> use FiniteField(4,1)?
    # not available).  Do Gaussian elimination over F_4 by hand.
    return f4_row_space(F, rows, n)


def f4_row_space(F, rows, ncols):
    rows = [list(r) for r in rows]
    piv = []
    r = 0
    for c in range(ncols):
        sel = None
        for i in range(r, len(rows)):
            if rows[i][c]:
                sel = i
                break
        if sel is None:
            continue
        rows[r], rows[sel] = rows[sel], rows[r]
        inv = F.inv[rows[r][c]]
        rows[r] = [F.mul[inv][v] for v in rows[r]]
        for i in range(len(rows)):
            if i != r and rows[i][c]:
                f = rows[i][c]
                rows[i] = [F.sub(rows[i][j], F.mul[f][rows[r][j]])
                           for j in range(ncols)]
        piv.append(c)
        r += 1
        if r == len(rows):
            break
    return [tuple(x) for x in rows[:r]], piv


def f4_in_span(F, basis, piv, v, ncols):
    v = list(v)
    for row, c in zip(basis, piv):
        if v[c]:
            f = v[c]
            v = [F.sub(v[j], F.mul[f][row[j]]) for j in range(ncols)]
    return all(x == 0 for x in v)


def generator_poly(F, code_basis, piv, n):
    """least-degree monic polynomial lying in the F_4-cyclic code spanned by
    code_basis (assumed shift-invariant).  Returns None if only 0."""
    for d in range(0, n + 1):
        for tail in itertools.product(range(F.q), repeat=d):
            poly = list(tail) + [1]
            v = tuple(poly[i] if i < len(poly) else 0 for i in range(n))
            if f4_in_span(F, code_basis, piv, v, n):
                return poly
    return None


