def build_phi():
    """isomorphism F_4 = FiniteField(2,2) -> <I, omega> subset A.
    In FiniteField(2,2) the element 2 (= "x") has multiplicative order 3."""
    F4 = FiniteField(2, 2)
    g = None
    for a in range(1, F4.q):
        if F4.order[a] == 3:
            g = a
            break
    assert g is not None
    table = {0: ZERO, 1: ONE, g: OMEGA, F4.mul[g][g]: OMEGA2}
    phi = [None] * 4
    for a in range(4):
        phi[a] = table[a]
    # verify it is a ring homomorphism
    for a in range(4):
        for b in range(4):
            assert phi[F4.add[a][b]] == ADD[phi[a]][phi[b]]
            assert phi[F4.mul[a][b]] == MUL[phi[a]][phi[b]]
    return F4, phi, g


