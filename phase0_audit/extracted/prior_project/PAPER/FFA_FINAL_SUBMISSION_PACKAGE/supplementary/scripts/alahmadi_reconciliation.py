# A = M_2(F_2).  index convention:  M = [[a,b],[c,d]]  ->  a*8+b*4+c*2+d
# ---------------------------------------------------------------------------
def m2(a, b, c, d):
    return a * 8 + b * 4 + c * 2 + d


def m2mul(x, y):
    a, b, c, d = (x >> 3) & 1, (x >> 2) & 1, (x >> 1) & 1, x & 1
    e, f, g, h = (y >> 3) & 1, (y >> 2) & 1, (y >> 1) & 1, y & 1
    return m2((a * e + b * g) & 1, (a * f + b * h) & 1,
              (c * e + d * g) & 1, (c * f + d * h) & 1)


MUL = [[m2mul(x, y) for y in range(16)] for x in range(16)]
ADD = [[x ^ y for y in range(16)] for x in range(16)]


def bits(x):
    return ((x >> 3) & 1, (x >> 2) & 1, (x >> 1) & 1, x & 1)


ZERO = m2(0, 0, 0, 0)                     # 0
ONE = m2(1, 0, 0, 1)                      # identity
OMEGA = m2(0, 1, 1, 1)                    # [[0,1],[1,1]]  (the paper's omega)
OMEGA2 = m2(1, 1, 1, 0)                   # omega^2
II = m2(0, 1, 1, 0)                       # [[0,1],[1,0]]  (the paper's i)
UU = ADD[ONE][II]                         # u = 1 + i


