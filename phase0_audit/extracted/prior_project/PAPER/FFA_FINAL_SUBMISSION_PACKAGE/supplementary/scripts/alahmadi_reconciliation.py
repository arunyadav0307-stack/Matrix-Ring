def flat_A(a):
    return tuple(bits(a))


def to_flat(words):
    """words: tuple of n elements of A -> F_2 vector of length 4n"""
    out = []
    for a in words:
        out.extend(bits(a))
    return tuple(out)


def from_flat(v):
    n = len(v) // 4
    out = []
    for e in range(n):
        b = v[4 * e:4 * e + 4]
        out.append(m2(*b))
    return tuple(out)


def rn_rmul(x, a, n):
    return to_flat(tuple(MUL[w][a] for w in from_flat(x)))


def rn_lmul(x, a, n):
    return to_flat(tuple(MUL[a][w] for w in from_flat(x)))


def rn_shift(x, n):
    w = from_flat(x)
    return to_flat(tuple([w[-1]] + list(w[:-1])))


F2 = FiniteField(2, 1)


def span2(vecs, N):
    if not vecs:
        return []
    return row_space_basis(F2, vecs, N)


def key(basis):
    return tuple(sorted(basis))


def enumerate_right_ideals(n):
    """exhaustive: lattice closure of all principal right ideals of R_n."""
    N = 4 * n
    allv = itertools.product(range(2), repeat=N)
    ops = [lambda v: rn_shift(v, n)]
    for a in range(16):
        ops.append((lambda a: (lambda v: rn_rmul(v, a, n)))(a))
    seen = {key([]): []}
    count = 0
    for v in allv:
        count += 1
        if not any(v):
            continue
        cur = span2([v], N)
        changed = True
        while changed:
            changed = False
            new = list(cur)
            for w in cur:
                for op in ops:
                    new.append(op(w))
            nv = span2(new, N)
            if len(nv) != len(cur):
                cur = nv
                changed = True
        seen[key(cur)] = cur
    ideals = list(seen.values())
    changed = True
    while changed:
        changed = False
        cur = list(ideals)
        for i in range(len(cur)):
            for j in range(i + 1, len(cur)):
                s = span2(list(cur[i]) + list(cur[j]), N)
                if key(s) not in seen:
                    seen[key(s)] = s
                    ideals.append(s)
                    changed = True
    return ideals, count


